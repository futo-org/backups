func fixtureGit(t *testing.T, repository string, args ...string) string {
	t.Helper()
	command := exec.Command("git", append([]string{"-C", repository, "-c", "user.name=Source fixture", "-c", "user.email=source@example.test"}, args...)...)
	data, err := command.CombinedOutput()
	if err != nil {
		t.Fatalf("git %v: %s: %v", args, data, err)
	}
	return strings.TrimSpace(string(data))
}

func writeFixture(t *testing.T, repository, filename, content string) {
	t.Helper()
	fullPath := filepath.Join(repository, filename)
	if err := os.MkdirAll(filepath.Dir(fullPath), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(fullPath, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

func newGitFixture(t *testing.T) string {
	t.Helper()
	if _, err := exec.LookPath("git"); err != nil {
		t.Skip("git unavailable")
	}
	repository := t.TempDir()
	fixtureGit(t, repository, "init", "-b", "main")
	for filename, content := range map[string]string{
		"src/main.ts": "export const fixed = false;\n", "docs/CHANGELOG.md": "First release\n", "README.md": "Committed documentation\n",
		".env.example": "PUBLIC_TEMPLATE=replace-me", "src/main.spec.ts": "test source", "pnpm-lock.yaml": "lockfile", "node_modules/library/index.ts": "dependency", "src/generated.go": "// Code generated by fixture. DO NOT EDIT.\npackage source", "image.png": "binary", "src/binary.ts": "\x00binary",
	} {
		writeFixture(t, repository, filename, content)
	}
	if err := os.Symlink("/etc/passwd", filepath.Join(repository, "src", "link.ts")); err != nil {
		t.Fatal(err)
	}
	fixtureGit(t, repository, "add", ".")
	fixtureGit(t, repository, "commit", "-m", "feat: initial release")
	fixtureGit(t, repository, "tag", "v1.0.0")
	writeFixture(t, repository, "src/main.ts", "export const fixed = true;\n")
	writeFixture(t, repository, "docs/CHANGELOG.md", "Fix backup retry in v1.1.0\n")
	fixtureGit(t, repository, "add", ".")
	fixtureGit(t, repository, "commit", "-m", "fix: backup retry")
	fixtureGit(t, repository, "tag", "-a", "v1.1.0", "-m", "v1.1.0")
	writeFixture(t, repository, "src/large.ts", strings.Repeat("x", source.MaxFileBytes+1))
	fixtureGit(t, repository, "add", ".")
	fixtureGit(t, repository, "commit", "-m", "chore: fixture oversized source")
	writeFixture(t, repository, "README.md", "Uncommitted documentation must not be archived\n")
	return repository
}

func TestBuildRepositoryRejectsCurrentAndHistoricalSecretFiles(t *testing.T) {
	for _, scenario := range []string{"current", "deleted", "tag only", "renamed public blob"} {
		t.Run(scenario, func(t *testing.T) {
			repository := newGitFixture(t)
			publicHead := fixtureGit(t, repository, "rev-parse", "HEAD")
			secret := []byte("SYNTHETIC_BUILD_SECRET_MUST_NOT_PUBLISH")
			if scenario == "renamed public blob" {
				writeFixture(t, repository, "public.txt", string(secret))
				fixtureGit(t, repository, "add", "public.txt")
				fixtureGit(t, repository, "commit", "-m", "fixture public file")
				fixtureGit(t, repository, "mv", "public.txt", ".env")
			} else {
				writeFixture(t, repository, ".env", string(secret))
				fixtureGit(t, repository, "add", ".env")
			}
			fixtureGit(t, repository, "commit", "-m", "fixture secret path")
			secretCommit := fixtureGit(t, repository, "rev-parse", "HEAD")
			secretBlob := fixtureGit(t, repository, "rev-parse", "HEAD:.env")
			switch scenario {
			case "deleted", "renamed public blob":
				fixtureGit(t, repository, "rm", ".env")
				fixtureGit(t, repository, "commit", "-m", "fixture removes secret path")
			case "tag only":
				fixtureGit(t, repository, "tag", "v0.9.0")
				fixtureGit(t, repository, "reset", "--hard", publicHead)
			}
			output := filepath.Join(t.TempDir(), "repository")

			err := buildRepository(context.Background(), repository, output)

			if err == nil {
				recovered, readErr := exec.Command("git", "-C", output, "cat-file", "blob", secretBlob).Output()
				if readErr == nil && bytes.Equal(recovered, secret) {
					t.Error("published artifact contains the synthetic secret object")
				}
				t.Fatal("build accepted a secret-bearing reachable commit")
			}
			if !strings.Contains(err.Error(), ".env") || !strings.Contains(err.Error(), secretCommit) || strings.Contains(err.Error(), string(secret)) {
				t.Fatalf("rejection must identify only path and commit: %v", err)
			}
			if _, err := os.Stat(output); !os.IsNotExist(err) {
				t.Fatalf("failed build published an artifact: %v", err)
			}
			leftovers, err := filepath.Glob(filepath.Join(filepath.Dir(output), ".embedded-git-*"))
			if err != nil || len(leftovers) != 0 {
				t.Fatalf("failed build retained temporary Git objects: %v %v", leftovers, err)
			}
		})
	}
}

func TestBuildRepositoryIncludesExactReleasesAndHistory(t *testing.T) {
	repository := newGitFixture(t)
	output := filepath.Join(t.TempDir(), "repository")
	if err := buildRepository(context.Background(), repository, output); err != nil {
		t.Fatal(err)
	}
	archive, err := source.Open(os.DirFS(output))
	if err != nil {
		t.Fatal(err)
	}
	metadata := archive.Metadata()
	if metadata.Head != fixtureGit(t, repository, "rev-parse", "HEAD") {
		t.Fatal("embedding rewrote the build commit")
	}
	if metadata.Shallow || metadata.DiscoveredTags != 2 || len(metadata.Revisions) != 3 || metadata.Revisions[0].Complete || metadata.Revisions[0].SkippedFiles != 1 || !metadata.Revisions[1].Complete || metadata.Revisions[1].Ref != "v1.1.0" {
		t.Fatalf("unexpected coverage: %+v", metadata)
	}
	for _, test := range []struct{ ref, content string }{{"1.0.0", "export const fixed = false;"}, {"1.1.0", "export const fixed = true;"}} {
		page, err := archive.ReadFile(test.ref, "src/main.ts", 1, 10)
		if err != nil || len(page.Lines) != 1 || page.Lines[0].Text != test.content {
			t.Fatalf("unexpected versioned source: %+v %v", page, err)
		}
		if page.Revision.Commit != fixtureGit(t, repository, "rev-parse", "v"+test.ref+"^{commit}") {
			t.Fatalf("embedding rewrote release %s", test.ref)
		}
	}
	page, err := archive.ReadFile("HEAD", "README.md", 1, 10)
	if err != nil || page.Lines[0].Text != "Committed documentation" {
		t.Fatalf("archive used working-tree changes: %+v %v", page, err)
	}
	files, err := archive.ListFiles("HEAD", "", 0, 100)
	if err != nil || files.Total != 3 {
		t.Fatalf("unexpected paths: %+v %v", files, err)
	}
	history, err := archive.ReleaseLog("1.1.0", 0, 100)
	if err != nil || history.Revision.HistoryBase != "v1.0.0" || !history.Revision.HistoryComplete || len(history.Commits) != 1 || history.Commits[0].Subject != "fix: backup retry" {
		t.Fatalf("unexpected release history: %+v %v", history, err)
	}
	if _, err := os.Stat(filepath.Join(output, "objects")); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(filepath.Join(output, "hooks")); !os.IsNotExist(err) {
		t.Fatal("hooks included in embedded repository")
	}
	if _, err := os.Stat(filepath.Join(output, "source.zip")); !os.IsNotExist(err) {
		t.Fatal("ZIP source archive included")
	}

}

func TestBuildRepositoryMarksShallowHistoryAndMissingVersionsUnavailable(t *testing.T) {
	repository := newGitFixture(t)
	clone := filepath.Join(t.TempDir(), "clone")
	fixtureGit(t, filepath.Dir(clone), "clone", "--depth=1", "file://"+repository, clone)
	output := filepath.Join(t.TempDir(), "repository")
	if err := buildRepository(context.Background(), clone, output); err != nil {
		t.Fatal(err)
	}
	archive, err := source.Open(os.DirFS(output))
	if err != nil {
		t.Fatal(err)
	}
	metadata := archive.Metadata()
	if !metadata.Shallow || metadata.Revisions[0].HistoryComplete {
		t.Fatalf("shallow history hidden: %+v", metadata)
	}
	if _, err := archive.ReadFile("1.0.0", "src/main.ts", 1, 1); err == nil {
		t.Fatal("missing version silently used HEAD")
	}
}

func TestBuildRepositoryDoesNotInferAdditionsOrDeletionsFromOmittedSource(t *testing.T) {
	repository := newGitFixture(t)
	files := map[string]string{
		"src/oversized.ts":       strings.Repeat("x", source.MaxFileBytes+1),
		"src/generated-state.ts": "// Code generated by fixture. DO NOT EDIT.\nexport const generated = true;\n",
		"src/binary-state.ts":    "\x00binary source",
	}
	for filename, text := range files {
		writeFixture(t, repository, filename, text)
	}
	fixtureGit(t, repository, "add", ".")
	fixtureGit(t, repository, "commit", "-m", "feat: omitted source fixture")
	fixtureGit(t, repository, "tag", "v1.2.0")
	for filename := range files {
		writeFixture(t, repository, filename, "export const fixed = true;\n")
	}
	fixtureGit(t, repository, "add", ".")
	fixtureGit(t, repository, "commit", "-m", "fix: archive eligible source")
	output := filepath.Join(t.TempDir(), "repository")
	if err := buildRepository(context.Background(), repository, output); err != nil {
		t.Fatal(err)
	}
	archive, err := source.Open(os.DirFS(output))
	if err != nil {
		t.Fatal(err)
	}
	for filename := range files {
		t.Run(filename, func(t *testing.T) {
			for _, direction := range []struct{ from, to string }{{"v1.2.0", "HEAD"}, {"HEAD", "v1.2.0"}} {
				comparison, err := archive.Compare(direction.from, direction.to, filename, 0, 10)
				if err != nil || comparison.Status != "unavailable" {
					t.Fatalf("omitted source was mistaken for a Git addition or deletion: %+v %v", comparison, err)
				}
				available := comparison.To
				if direction.from == "HEAD" {
					available = comparison.From
				}
				if available == nil || len(available.Lines) != 1 || available.Lines[0].Text != "export const fixed = true;" {
					t.Fatalf("available source evidence was lost: %+v", comparison)
				}
				if direction.from == "HEAD" && comparison.To != nil || direction.to == "HEAD" && comparison.From != nil {
					t.Fatalf("unarchived source evidence was invented: %+v", comparison)
				}
			}
		})
	}
}

func TestImageBuildWorkflowsFetchColumboReleaseHistory(t *testing.T) {
	for _, test := range []struct{ filename, job, conditionalDepth string }{
		{"build-check.yml", "build", "${{ matrix.app == 'columbo' && '0' || '1' }}"},
		{"deploy.yml", "build", "${{ matrix.app.package == 'columbo' && '0' || '1' }}"},
		{"release-images.yml", "images", "0"},
	} {
		t.Run(test.filename, func(t *testing.T) {
			data, err := os.ReadFile(filepath.Join("..", "..", "..", "..", ".github", "workflows", test.filename))
			if err != nil {
				t.Fatal(err)
			}
			var workflow struct {
				Jobs map[string]struct {
					Steps []struct {
						Uses string
						With map[string]string
					}
				}
			}
			if err := yaml.Unmarshal(data, &workflow); err != nil {
				t.Fatal(err)
			}
			for _, step := range workflow.Jobs[test.job].Steps {
				if !strings.HasPrefix(step.Uses, "actions/checkout@") {
					continue
				}
				depth := step.With["fetch-depth"]
				if depth != "0" && depth != test.conditionalDepth {
					t.Fatalf("Columbo source archive requires complete release history: fetch-depth=%q", depth)
				}
				return
			}
			t.Fatal("image build checkout unavailable")
		})
	}
}

