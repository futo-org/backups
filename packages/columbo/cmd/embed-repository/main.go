package main

import (
	"context"
	"flag"
	"fmt"
	"io/fs"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"time"

	"columbo/internal/source"
)

const buildTimeout = 10 * time.Minute

func main() {
	repository := flag.String("repo", ".", "Git working tree")
	output := flag.String("output", "internal/source/embedded", "Output embedded Git directory")
	flag.Parse()
	ctx, cancel := context.WithTimeout(context.Background(), buildTimeout)
	defer cancel()
	if err := buildRepository(ctx, *repository, *output); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func buildRepository(ctx context.Context, repository, output string) error {
	repository, err := filepath.Abs(repository)
	if err != nil {
		return err
	}
	temporary, err := os.MkdirTemp(filepath.Dir(output), ".embedded-git-*")
	if err != nil {
		return err
	}
	defer func() { _ = os.RemoveAll(temporary) }()
	git := func(args ...string) ([]byte, error) {
		command := exec.CommandContext(ctx, "git", args...)
		data, err := command.CombinedOutput()
		if err != nil {
			return nil, fmt.Errorf("git %s: %w: %s", args[0], err, data)
		}
		return data, nil
	}
	if _, err := git("init", "--bare", temporary); err != nil {
		return err
	}
	if _, err := git("-C", temporary, "fetch", "--update-shallow", "--no-tags", "--no-write-fetch-head", repository, "HEAD", "+refs/tags/*:refs/tags/*"); err != nil {
		return err
	}
	head, err := git("-C", repository, "rev-parse", "--verify", "HEAD^{commit}")
	if err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(temporary, "HEAD"), []byte(strings.TrimSpace(string(head))+"\n"), 0o644); err != nil {
		return err
	}
	if err := rejectSecretPaths(ctx, temporary); err != nil {
		return err
	}
	if _, err := git("-C", temporary, "repack", "-a", "-d"); err != nil {
		return err
	}
	for _, name := range []string{"hooks", "info", "description", "branches", "FETCH_HEAD", "logs"} {
		if err := os.RemoveAll(filepath.Join(temporary, name)); err != nil {
			return err
		}
	}
	if err := os.WriteFile(filepath.Join(temporary, "config"), []byte("[core]\n\trepositoryformatversion = 0\n\tbare = true\n"), 0o644); err != nil {
		return err
	}
	var size int64
	err = filepath.WalkDir(temporary, func(name string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if entry.IsDir() {
			return nil
		}
		info, err := entry.Info()
		if err != nil {
			return err
		}
		if !info.Mode().IsRegular() {
			return fmt.Errorf("non-regular embedded Git file: %s", name)
		}
		size += info.Size()
		if size > source.MaxRepositoryBytes {
			return fmt.Errorf("embedded Git repository exceeds size limit")
		}
		return nil
	})
	if err != nil {
		return err
	}
	if _, err := source.Open(os.DirFS(temporary)); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(temporary, "README.txt"), []byte("Build-time bare Git repository; generated by cmd/embed-repository before compiling Columbo.\n"), 0o644); err != nil {
		return err
	}
	if err := os.RemoveAll(output); err != nil {
		return err
	}
	if err := os.Rename(temporary, output); err != nil {
		return err
	}
	fmt.Fprintf(os.Stderr, "Embedded Git repository: %s, %d bytes\n", strings.TrimSpace(string(head)), size)
	return nil
}
